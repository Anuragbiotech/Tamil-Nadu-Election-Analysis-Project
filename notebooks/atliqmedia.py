"""#Vote Share Story"""

# Calculate total votes polled in each constituency for 2021

total_votes_2021 = (
    tn_2021_results
    .groupby('ac_number')['votes']
    .sum()
    .reset_index(name='total_votes_2021')
)

# Calculate total votes polled in each constituency for 2026

total_votes_2026 = (
    tn_2026_results
    .groupby('ac_number')['votes']
    .sum()
    .reset_index(name='total_votes_2026')
)

# Merge total constituency votes into both election datasets
# so that each candidate row also contains the total votes polled
# in that constituency for percentage and comparative analysis.

tn_2021_results = pd.merge(
    tn_2021_results,
    total_votes_2021,
    on='ac_number'
)

# Merge total constituency votes into both election datasets
# so that each candidate row also contains the total votes polled
# in that constituency for percentage and comparative analysis.

tn_2026_results = pd.merge(
    tn_2026_results,
    total_votes_2026,
    on='ac_number'
)

# Calculate candidate vote share percentage for 2021

tn_2021_results['vote_share_2021'] = (
    tn_2021_results['votes']
    / tn_2021_results['total_votes_2021']
) * 100

# Aggregate party vote share statewide - 2021
vote_share_2021 = (
    tn_2021_results
    .groupby('party')['votes']
    .sum()
    .reset_index(name='votes_2021')
)

# Aggregate party vote share statewide - 2026
vote_share_2026 = (
    tn_2026_results
    .groupby('party')['votes']
    .sum()
    .reset_index(name='votes_2026')
)

# Merge statewide totals
vote_share_comparison = pd.merge(
    vote_share_2021,
    vote_share_2026,
    on='party',
    how='outer'
).fillna(0)

# Calculate vote-share change
vote_share_comparison['vote_change'] = (
    vote_share_comparison['votes_2026']
    - vote_share_comparison['votes_2021']
)

# Sort parties by highest increase in votes
# between the 2021 and 2026 elections

vote_share_comparison.sort_values(
    by='vote_change',
    ascending=False
)


