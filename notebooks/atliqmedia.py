"""
Merge the 2021 and 2026 regional seat distribution tables
to compare how party-wise seat counts changed across regions
between the two elections.
"""

regional_shift = pd.merge(
    region_2021,
    region_2026,
    on=['region', 'party'],
    how='outer'
)

